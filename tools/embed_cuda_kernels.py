#!/usr/bin/env python3
"""Embed common kernel sources and structural networks at build time.

The installed executable generates candidate constants with GMP. Python is
needed only to build the executable or run the standalone calibration tool.
"""

from pathlib import Path
import importlib.util
import json
import sys

root = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    "reference", root / "tools/packed_parameters.py"
)
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)
source = (root / "kernels/src/packed.cl").read_text()
source = source[
    : source.index("__kernel __attribute__((reqd_work_group_size(PG_OUTER_THREADS")
]
lines = [
    "// Generated by tools/embed_cuda_kernels.py; do not edit.",
    "#pragma once",
    "#include <cstdint>",
    '#include "cuda/profiles.h"',
    "namespace cuda_gfn { namespace embedded {",
]


def string(name, value):
    assert ')GENEFER"' not in value
    lines.append(
        "inline constexpr const char " + name + '[] = R"GENEFER(' + value + ')GENEFER";'
    )


string("packed_base", source)
string("converter", (root / "kernels/src/packed-convert.clh").read_text())
string("codec", (root / "kernels/src/packed-codec.clh").read_text())
string("three_prime", (root / "kernels/src/three-prime.cl").read_text())
for outer in (16, 64, 256, 1024):
    string("outer_" + str(outer), reference.outer_source(outer))
for inner in (16, 32, 64, 128, 256, 512, 1024, 2048, 4096, 8192):
    string("inner_" + str(inner), reference.inner_source(inner))
for ln in range(14, 23):
    for count in range(32, 1, -1):
        try:
            p, g = reference.field_pool(count, 1 << ln)
            break
        except reference.UnsupportedPackedParameters:
            continue
    else:
        raise RuntimeError("No supported prime pool")
    lines.append(
        "inline constexpr unsigned prime_count_" + str(ln) + " = " + str(count) + ";"
    )
    for name, values in [("primes", p), ("roots", g)]:
        lines.append(
            "inline constexpr uint32_t "
            + name
            + "_"
            + str(ln)
            + "["
            + str(count)
            + "] = {"
            + ",".join(str(x) + "u" for x in values)
            + "};"
        )
profiles = json.loads((root / "profiles/nvidia.json").read_text())


def profile(name, memory, arch, n, p):
    kind = {"packed": "packed", "three-prime": "three_prime",
            "original-cuda": "original_cuda", "original-opencl": "original_opencl"}[p["implementation"]]
    length = p.get("length", 65536)
    fields = [
        length,
        (1 << int(n)) // length,
        p.get("outer", 64),
        p.get("chunk", 8),
        p.get("inner_blocks", 1),
        p.get("root_bits", 32),
        p.get("digit_ratio", 3),
        0,
        str(p.get("matrix_mad", False)).lower(),
        str(p.get("inline_converter", False)).lower(),
    ]
    return (
        "{"
        + json.dumps(name)
        + ","
        + str(memory)
        + ","
        + n
        + ",architecture::"
        + arch
        + ",implementation::"
        + kind
        + ",{"
        + ",".join(map(str, fields))
        + "},"
        + str(p.get("shared_memory_preference", 50))
        + "}"
    )


for table in ["device_profiles", "architecture_profiles", "project_profiles"]:
    entries = []
    if table == "device_profiles":
        for d in profiles["devices"]:
            for n, p in d["projects"].items():
                entries.append(
                    profile(d["name"], d["memory_gib"], d["architecture"], n, p)
                )
    elif table == "architecture_profiles":
        for arch, projects in profiles["architectures"].items():
            for n, p in projects.items():
                entries.append(profile(arch, 0, arch, n, p))
    else:
        for n, p in profiles["defaults"].items():
            entries.append(profile("GFN-" + n + " default", 0, "unknown", n, p))
    lines.append(
        "inline constexpr profile_entry "
        + table
        + "[] = {\n"
        + ",\n".join(entries)
        + "\n};"
    )
lines.append("} } // namespace cuda_gfn::embedded")
out = (
    Path(sys.argv[1])
    if len(sys.argv) > 1
    else root / "build/generated/cuda/embedded_kernels.h"
)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines) + "\n")
